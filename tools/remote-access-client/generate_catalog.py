"""Generate the optional client bridge table from the server's facility catalog."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
panels = {
    'shop': 'shop', 'fish-market': 'fishMarket', 'cafe': 'cafe',
    'workshop': 'workshop', 'shop-workshop-store': 'shopWorkshopStore',
    'shop-workshop-repair': 'shopWorkshopRepair',
}

def generate():
    catalog = json.loads((root / 'internal/gameserver/assets/remote_facilities.json').read_text(encoding='utf8'))
    lines = ['// Generated by generate_catalog.py; do not edit.', 'static const Facility facilities[] = {']
    quote = lambda value: 'L' + json.dumps(value, ensure_ascii=False)
    for level, rows in sorted(catalog.items()):
        for row in rows:
            fields = [quote(level), str(row['code']), quote(row['name']), quote(row['category']), quote(row['id']), panels[row['panel']]]
            lines.append('    {' + ','.join(fields) + '},')
    return '\n'.join(lines + ['};', ''])

if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = Path(__file__).with_name('remote-facilities.h')
    content = generate()
    if args.check:
        if not output.exists() or output.read_text(encoding='utf8') != content:
            raise SystemExit('Client facility table is out of date; run generate_catalog.py.')
    else:
        output.write_text(content, encoding='utf8')
